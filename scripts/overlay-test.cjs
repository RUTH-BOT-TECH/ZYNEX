/**
 * scripts/overlay-test.cjs — the ffmpeg image effects must actually render.
 *
 * Two production-only traps are guarded here:
 *   1. ffmpeg-static is built WITHOUT drawtext (493 filters, no drawtext), so
 *      any text overlay dies with "No such filter". The container also has no
 *      system fonts at all. A filter string can look perfectly reasonable and
 *      be impossible to run.
 *   2. lib/handler.js used to discard what a command returned, so an engine
 *      that produced an image delivered nothing and reported no error.
 */

const assert = require('assert');
const fs = require('fs');
const path = require('path');
const os = require('os');
const { execFileSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const engine = require(path.join(ROOT, 'lib/engines/overlay.js'));
const I = engine._internal;
const { ffmpegPath } = require(path.join(ROOT, 'lib/ffmpeg'));

let pass = 0, fail = 0;
const tests = [];
const t = (name, fn) => tests.push([name, fn]);

/* a real 240x240 test pattern, generated by ffmpeg itself */
const TMP = fs.mkdtempSync(path.join(os.tmpdir(), 'zynex-ovt-'));
const BASE = path.join(TMP, 'base.png');
execFileSync(ffmpegPath(), ['-y', '-loglevel', 'error', '-f', 'lavfi',
  '-i', 'testsrc=size=240x240:rate=1', '-frames:v', '1', '-update', '1', BASE]);
const IMG = fs.readFileSync(BASE);

/* ── environment invariants ───────────────────────────────── */
t('ffmpeg build has no drawtext, so no effect may use it', () => {
  const list = execFileSync(ffmpegPath(), ['-hide_banner', '-filters']).toString();
  const hasDrawtext = /\bdrawtext\b/.test(list);
  if (hasDrawtext) return; // different build — the constraint is moot

  for (const [name, def] of Object.entries(I.EFFECTS)) {
    const chain = def.args();
    assert.ok(!/drawtext/.test(chain), `${name} uses drawtext, which this ffmpeg cannot run`);
  }
});

t('every filter named in every chain exists in this build', () => {
  const list = execFileSync(ffmpegPath(), ['-hide_banner', '-filters']).toString();
  const known = new Set(
    list.split('\n').map((l) => l.trim().split(/\s+/)[1]).filter(Boolean),
  );
  for (const [name, def] of Object.entries(I.EFFECTS)) {
    const chain = def.args();
    // pull bare filter names: "x=y" head segments
    const names = chain.split(/[,;]/).map((part) => part.trim().split('=')[0].replace(/\[.*?\]/g, '')).filter(Boolean);
    for (const n of names) {
      if (!n || n.includes('=') || /^\d/.test(n)) continue;
      assert.ok(known.has(n), `${name} uses filter "${n}" which this ffmpeg does not provide`);
    }
  }
});

/* ── rendering ────────────────────────────────────────────── */
t('every effect renders a real PNG', async () => {
  const failures = [];
  for (const [name, def] of Object.entries(I.EFFECTS)) {
    try {
      const out = await I.render(IMG, def.args());
      if (!out || out.length < 100) failures.push(`${name}: only ${out ? out.length : 0} bytes`);
      else if (out.slice(1, 4).toString() !== 'PNG') failures.push(`${name}: not a PNG (${out.slice(1, 4)})`);
    } catch (e) {
      failures.push(`${name}: ${e.message.slice(0, 60)}`);
    }
  }
  assert.deepStrictEqual(failures, [], 'effects failed:\n  ' + failures.join('\n  '));
});

t('an effect actually changes the image', async () => {
  // A filter chain that silently no-ops would still return a valid PNG.
  const out = await I.render(IMG, I.EFFECTS.jail.args());
  assert.notStrictEqual(out.length, IMG.length, 'jail returned byte-identical input');
  const hash = (b) => require('crypto').createHash('sha1').update(b).digest('hex');
  assert.notStrictEqual(hash(out), hash(IMG), 'jail output is identical to the input');
});

t('greyscale effects produce greyscale pixels', async () => {
  const out = await I.render(IMG, I.EFFECTS.trash.args());
  // decode via ffmpeg to raw RGB and check channel spread
  const raw = execFileSync(ffmpegPath(), ['-loglevel', 'error', '-i', 'pipe:0', '-f', 'rawvideo',
    '-pix_fmt', 'rgb24', 'pipe:1'], { input: out, maxBuffer: 64 * 1024 * 1024 });
  let spread = 0;
  for (let i = 0; i + 2 < raw.length; i += 3 * 97) {
    spread += Math.abs(raw[i] - raw[i + 1]) + Math.abs(raw[i + 1] - raw[i + 2]);
  }
  assert.ok(spread < raw.length, `trash is not greyscale (channel spread ${spread})`);
});

/* ── failure paths ────────────────────────────────────────── */
t('no image produces an instruction, not a crash', async () => {
  let said = null;
  await engine.execute({
    command: 'wasted',
    reply: (x) => { said = String(x); return Promise.resolve(); },
    download: async () => { throw new Error('no media in this message'); },
  });
  assert.ok(/Reply to a photo/i.test(said), `expected guidance, got: ${said}`);
  assert.ok(/wasted/.test(said));
});

t('a broken image is reported, not swallowed', async () => {
  let said = null;
  await engine.execute({
    command: 'jail',
    reply: (x) => { said = String(x); return Promise.resolve(); },
    download: async () => Buffer.from('this is definitely not an image'),
  });
  assert.ok(/failed/i.test(said), `expected a failure message, got: ${said}`);
  assert.ok(/ffmpeg could not process|could not process/i.test(said), 'did not say what went wrong');
});

/* ── ownership: no duplicate command names ────────────────── */
t('the engine does not claim names something real already owns', () => {
  for (const reserved of ['delete', 'kiss', 'slap', 'hug', 'pat', 'tourl']) {
    assert.ok(!engine.match(reserved), `${reserved} would shadow an existing command`);
  }
});

t('effects are registered but not owned twice', () => {
  // Every claimed name must exist in EFFECTS and vice versa — a name in
  // extraNames with no entry would resolve to the fallback stub instead.
  const claimed = new Set(engine.extraNames);
  for (const name of Object.keys(I.EFFECTS)) {
    assert.ok(claimed.has(name), `${name} has an effect but is not claimed`);
  }
});

/* ── the handler must deliver what a command returns ──────── */
t('handler sends a returned image instead of discarding it', () => {
  const src = fs.readFileSync(path.join(ROOT, 'lib/handler.js'), 'utf8');
  assert.ok(/const result = await command\.execute/.test(src),
    'the return value of execute() is discarded again — media commands would silently send nothing');
  assert.ok(/Buffer\.isBuffer\(result\.image\)/.test(src), 'no image delivery after execute()');
  assert.ok(/Buffer\.isBuffer\(result\.audio\)/.test(src), 'no audio delivery after execute()');
});

t('handler reports a failed artefact send', () => {
  const src = fs.readFileSync(path.join(ROOT, 'lib/handler.js'), 'utf8');
  assert.ok(/produced a result but sending it failed/.test(src),
    'a failed send of returned media would be silent');
});

setTimeout(async () => {
  for (const [name, fn] of tests) {
    try { await fn(); console.log(`✔ ${name}`); pass++; }
    catch (e) { console.log(`✗ ${name}  ❌ ${e.message}`); fail++; }
  }
  try { fs.rmSync(TMP, { recursive: true, force: true }); } catch {}
  console.log(`\n${fail === 0 ? '✔' : '✗'} ${pass}/${pass + fail} passed`);
  process.exit(fail === 0 ? 0 : 1);
}, 50);
